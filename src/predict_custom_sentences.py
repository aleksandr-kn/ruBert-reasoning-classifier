def load_model(model_dir: str):
    """
    Загрзука модели
    """

    tokenizer = AutoTokenizer.from_pretrained(model_dir)
    model = AutoModelForSequenceClassification.from_pretrained(model_dir)

    device = torch.device(
        "mps" if torch.backends.mps.is_available()
        else "cuda" if torch.cuda.is_available()
        else "cpu"
    )
    model.to(device)

    return model, tokenizer, device

def predict(model, tokenizer, device, sentences):
    """
    Предсказание
    """
    inputs = tokenizer(
        [s["text"] for s in sentences],
        truncation=True,
        padding=True,
        max_length=128,
        return_tensors="pt"
    )

    inputs = {k: v.to(device) for k, v in inputs.items()}

    with torch.no_grad():
        logits = model(**inputs).logits
        probs = torch.softmax(logits, dim=1)
        preds = torch.argmax(probs, dim=1).cpu().tolist()
        probs = probs[:, 1].cpu().tolist()

    results = []
    for sent, true_label, pred_label, p in zip(sentences, [s["label"] for s in sentences], preds, probs):
        results.append({
            "text": sent['text'],
            "label": pred_label,
            "prob": p,
            "label_name": "рассуждение" if pred_label == 1 else "не рассуждение",
            "correct": int(true_label == pred_label)  # 1 если правильно, 0 если нет
        })

    return results

def main():
    parser = argparse.ArgumentParser(description="Predict custom sentences using RuBERT")
    parser.add_argument(
        "--model_dir",
        type=str,
        required=False,
        default="./pretrained/fine_tuned_rubert",
        help="Путь к сохранённой модели (директория с config.json и pytorch_model.bin)"
    )

    args = parser.parse_args()

    model, tokenizer, device = load_model(args.model_dir)

    all_sentences = []
    for lst in [custom_sentences_test, custom_sentences2, single_test, stress_test_sentences]:
        all_sentences.extend(lst)

    results = predict(model, tokenizer, device, all_sentences)

    for r in results:
        print(f"\nТекст: {r['text']}")
        print(f"Класс: {r['label']} ({r['label_name']})")
        print(f"Уверенность: {r['prob']:.4f}")
        print("-" * 50)

    # Подсчёт правильно предсказанных
    correct_count = sum(r['correct'] for r in results)
    total = len(results)
    print(f"\nИтого правильно предсказано: {correct_count} из {total} ({correct_count/total*100:.2f}%)")

if __name__ == "__main__":
    main()
