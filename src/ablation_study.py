def ablation(text, remove_tokens):
    """
    Убирает из текста все указанные токены/фразы (без учета регистра) через токенизацию.

    Args:
        text (str): исходный текст
        remove_tokens (list of str): слова или фразы, которые нужно убрать

    Returns:
        str: текст после удаления
    """

    # токены для удаления в нижнем регистре
    remove_tokens_lower = [t.lower() for t in remove_tokens]

    import re

    # простая токенизация через пробелы (можно заменить на spacy, если нужно)
    tokens = re.findall(r'\w+|\S', text)

    filtered_tokens = []
    for tok in tokens:
        if tok.lower() not in remove_tokens_lower:
            filtered_tokens.append(tok)

    # склеиваем обратно
    modified_text = " ".join(filtered_tokens)
    return modified_text

